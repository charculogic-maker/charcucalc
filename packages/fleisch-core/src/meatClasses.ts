export function toOsMeatFatClass(k: Fleischklasse): OsMeatFatClass {
  return {
    classId: k.id,
    code: k.code,
    name: k.name,
    proteinPercentage: k.beffe + k.be,
    collagenPercentage: k.be,
    fatPercentage: k.fett,
    waterPercentage: k.wasser,
    saturatedFatPercentage: k.ges_fs,
    tempSoll: k.temp_soll,
    lager: k.lager,
  };
}

/** OS catalog = shared meat classes (without EIS) + legacy aliases. */
export function buildOsGehaMeatClasses(
  legacy: OsMeatFatClass[] = OS_LEGACY_MEAT_CLASSES,
): OsMeatFatClass[] {
  const shared = Object.values(FLEISCHKLASSEN)
    .filter((k) => k.id !== "EIS")
    .map(toOsMeatFatClass);
  return [...shared, ...legacy];
}

export function getFleischklasse(id: string): Fleischklasse | undefined {
  return FLEISCHKLASSEN[id];
}

export function fleischklassenList(): Fleischklasse[] {
  return Object.values(FLEISCHKLASSEN);
}
